#!/usr/bin/env python3
"""Generate testbench/common/control_table.svh from docs/control_table.csv.

CSV format:
  * instr, opcode, funct3, instr30 form the match pattern. opcode and funct3
    are binary strings; 'x' in a pattern field matches anything.
  * The remaining columns are the expected control signals in decimal; 'x'
    means the value is not checked (its bits are 0 in ctrl_mask).
  * Patterns must not overlap. The single all-'x' pattern row is the default
    for every instruction not matched by another row.

The generated file is for testbenches only. The control unit RTL must not
include it, or the RTL would be checked against itself.

Usage:
  python3 scripts/gen_control_table.py          regenerate the .svh
  python3 scripts/gen_control_table.py --check  exit 1 if the .svh is stale
"""

import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_PATH = ROOT / "docs" / "control_table.csv"
SVH_PATH = ROOT / "testbench" / "common" / "control_table.svh"

PATTERN = [("opcode", 7), ("funct3", 3), ("instr30", 1)]
SIGNALS = [
    ("branch_decoder_on", 1),
    ("mux_PC", 1),
    ("mux_reg", 2),
    ("RegWrite", 1),
    ("MemWrite", 1),
    ("mux_ALUA", 2),
    ("mux_ALUB", 1),
    ("ALU_funct", 4),
    ("sign_val", 1),
    ("read_size", 2),
]


def fail(msg):
    sys.exit(f"{CSV_PATH.name}: {msg}")


def parse_pattern(row, line):
    fields = []
    for name, width in PATTERN:
        value = row[name].strip()
        if value != "x" and (len(value) != width or set(value) - {"0", "1"}):
            fail(f"line {line}: {name} must be {width} binary digits or x, got '{value}'")
        fields.append(value)
    return fields


def parse_signals(row, line):
    values = []
    for name, width in SIGNALS:
        value = row[name].strip()
        if value != "x":
            if not value.isdigit() or int(value) >= 2**width:
                fail(f"line {line}: {name} must be 0..{2**width - 1} or x, got '{value}'")
            value = int(value)
        values.append(value)
    return values


def overlaps(a, b):
    return all(x == "x" or y == "x" or x == y for x, y in zip(a, b))


def load_rows():
    with CSV_PATH.open(newline="") as f:
        reader = csv.DictReader(f)
        expected = ["instr"] + [n for n, _ in PATTERN] + [n for n, _ in SIGNALS]
        if reader.fieldnames != expected:
            fail(f"header must be: {','.join(expected)}")
        rows = []
        for line, row in enumerate(reader, start=2):
            rows.append((row["instr"].strip(), parse_pattern(row, line), parse_signals(row, line)))

    defaults = [r for r in rows if all(p == "x" for p in r[1])]
    if len(defaults) != 1:
        fail("need exactly one all-x default row")
    specific = [r for r in rows if r is not defaults[0]]
    for i, a in enumerate(specific):
        for b in specific[i + 1:]:
            if overlaps(a[1], b[1]):
                fail(f"{a[0]} and {b[0]} match overlapping encodings")
    return specific, defaults[0]


def sv_case_label(pattern):
    return "11'b" + "_".join("?" * w if p == "x" else p for p, (_, w) in zip(pattern, PATTERN))


def sv_value(value, width):
    return f"{width}'d{0 if value == 'x' else value}"


def sv_mask(value, width):
    return f"{width}'b{('0' if value == 'x' else '1') * width}"


def sv_signals(values, fmt=sv_value):
    return "{" + ", ".join(fmt(v, w) for v, (_, w) in zip(values, SIGNALS)) + "}"


def render(specific, default):
    struct_fields = "\n".join(
        f"    logic {f'[{w - 1}:0]' if w > 1 else '     '} {n};" for n, w in SIGNALS)
    expected_cases = "\n".join(
        f"        {sv_case_label(p)}: ctrl_expected = {sv_signals(v)}; // {n}"
        for n, p, v in specific)
    mask_cases = "\n".join(
        f"        {sv_case_label(p)}: ctrl_mask = {sv_signals(v, sv_mask)}; // {n}"
        for n, p, v in specific)
    name_cases = "\n".join(
        f"        {sv_case_label(p)}: ctrl_name = \"{n}\";" for n, p, _ in specific)
    diff_checks = "\n".join(
        f"    if (((actual.{n} ^ expected.{n}) & mask.{n}) !== '0)\n"
        f"        s = {{s, s == \"\" ? \"\" : \", \", "
        f"$sformatf(\"{n} exp %0d got %0d\", expected.{n}, actual.{n})}};"
        for n, _ in SIGNALS)
    args = "input logic [6:0] opcode, input logic [2:0] funct3, input logic instr30"

    return f"""/*
 Generated by scripts/gen_control_table.py from docs/control_table.csv.
 Do not edit by hand. Testbench use only: the control unit RTL must not include this file.
 ctrl_mask has 1s on the bits to check; a field that is x in the CSV is 0 in both
 ctrl_expected and ctrl_mask. Check with: ((actual ^ ctrl_expected(...)) & ctrl_mask(...)) !== '0
 ctrl_diff lists the checked fields that differ, for failure messages.
*/

`ifndef CONTROL_TABLE_SVH
`define CONTROL_TABLE_SVH

typedef struct packed {{
{struct_fields}
}} ctrl_t;

function automatic ctrl_t ctrl_expected({args});
    casez ({{opcode, funct3, instr30}})
{expected_cases}
        default: ctrl_expected = {sv_signals(default[2])}; // {default[0]}
    endcase
endfunction

function automatic ctrl_t ctrl_mask({args});
    casez ({{opcode, funct3, instr30}})
{mask_cases}
        default: ctrl_mask = {sv_signals(default[2], sv_mask)}; // {default[0]}
    endcase
endfunction

function automatic string ctrl_name({args});
    casez ({{opcode, funct3, instr30}})
{name_cases}
        default: ctrl_name = "{default[0]}";
    endcase
endfunction

function automatic string ctrl_diff(input ctrl_t actual, input ctrl_t expected, input ctrl_t mask);
    string s;
    s = "";
{diff_checks}
    return s;
endfunction

`endif
"""


def main():
    text = render(*load_rows())
    if "--check" in sys.argv[1:]:
        if not SVH_PATH.exists() or SVH_PATH.read_text() != text:
            sys.exit(f"{SVH_PATH.relative_to(ROOT)} is stale; run scripts/gen_control_table.py")
        return
    SVH_PATH.parent.mkdir(parents=True, exist_ok=True)
    SVH_PATH.write_text(text)
    print(f"wrote {SVH_PATH.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
